// node scripts/vendor-fonts.mjs <node_modules dir>
// Copies latin + latin-ext woff2 files from @fontsource packages into public/fonts
// and writes public/fonts/fonts.css with clean family names. Fonts are vendored so
// every render is identical on every machine (no network, no hosted stylesheets).
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const NM = process.argv[2] || 'node_modules';
const OUT = 'public/fonts';
mkdirSync(OUT, { recursive: true });

// [family name, package, css files to read]
const FONTS = [
  ['Archivo', '@fontsource-variable/archivo', ['standard.css']],
  ['Bricolage Grotesque', '@fontsource-variable/bricolage-grotesque', ['standard.css']],
  ['Unbounded', '@fontsource-variable/unbounded', ['index.css']],
  ['Anton', '@fontsource/anton', ['400.css']],
  ['Instrument Serif', '@fontsource/instrument-serif', ['400.css', '400-italic.css']],
  ['Fraunces', '@fontsource-variable/fraunces', ['standard.css', 'standard-italic.css']],
  ['Big Shoulders Display', '@fontsource-variable/big-shoulders-display', ['index.css']],
  ['Mona Sans', '@fontsource-variable/mona-sans', ['standard.css']],
  ['Hubot Sans', '@fontsource-variable/hubot-sans', ['standard.css']],
  ['Inter Tight', '@fontsource-variable/inter-tight', ['index.css']],
  ['JetBrains Mono', '@fontsource-variable/jetbrains-mono', ['index.css']],
  ['Dela Gothic One', '@fontsource/dela-gothic-one', ['400.css']],
  ['Gloock', '@fontsource/gloock', ['400.css']],
  ['Schibsted Grotesk', '@fontsource-variable/schibsted-grotesk', ['index.css']],
  ['Familjen Grotesk', '@fontsource-variable/familjen-grotesk', ['index.css']],
  ['Onest', '@fontsource-variable/onest', ['index.css']],
  ['Geist Mono', '@fontsource-variable/geist-mono', ['index.css']],
  ['Instrument Sans', '@fontsource-variable/instrument-sans', ['standard.css']],
  ['Figtree', '@fontsource-variable/figtree', ['index.css']],
  ['Funnel Display', '@fontsource-variable/funnel-display', ['index.css']],
  ['Funnel Sans', '@fontsource-variable/funnel-sans', ['index.css']],
  ['Host Grotesk', '@fontsource-variable/host-grotesk', ['index.css']],
  ['Sora', '@fontsource-variable/sora', ['index.css']],
];

let css = '/* Generated by scripts/vendor-fonts.mjs. SIL OFL fonts via Fontsource. */\n';
for (const [family, pkg, files] of FONTS) {
  for (const f of files) {
    const p = join(NM, pkg, f);
    if (!existsSync(p)) { console.warn('missing', p); continue; }
    const src = readFileSync(p, 'utf8');
    for (const block of src.split('@font-face').slice(1)) {
      const body = block.slice(block.indexOf('{') + 1, block.indexOf('}'));
      const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(body)?.[1];
      if (!file || !/-latin-(ext-)?/.test(file)) continue; // latin + latin-ext only
      copyFileSync(join(NM, pkg, 'files', file), join(OUT, file));
      const keep = body.split(';').map((s) => s.trim())
        .filter((s) => /^(font-style|font-weight|font-stretch|unicode-range)/.test(s));
      const fmt = /variations/.test(body) ? 'woff2-variations' : 'woff2';
      css += `@font-face{font-family:'${family}';font-display:block;${keep.join(';')};src:url(./${file}) format('${fmt}')}\n`;
    }
  }
}
writeFileSync(join(OUT, 'fonts.css'), css);
console.log('wrote', join(OUT, 'fonts.css'));
